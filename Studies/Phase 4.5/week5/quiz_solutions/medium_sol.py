def problem3_solution():
    print("\n" + "=" * 50)
    print("문제 3 해설: 불일치 쌍이 판단의 근거다")
    print("=" * 50 + "\n")
    print("답의 뼈대:")
    print("  (1) 집계 성공률")
    print("      zero-shot  = 3(둘 다) + 2(zero만) = 5/100 = 5%")
    print("      fine-tuned = 3(둘 다) + 9(fine만) = 12/100 = 12%")
    print()
    print("  (2) 정보를 주는 관측: 불일치 쌍 2 + 9 = 11개.")
    print("      나머지 89개(둘 다 성공 3 + 둘 다 실패 86)는 차이에 대해 말하지 않는다.")
    print("      -> N=100 이라도 차이 판정에 쓰이는 표본은 11개다. 이 사실을 알고")
    print("         보고해야 한다.")
    print()
    print("      부호검정으로 보면 11개 중 9개가 개선 방향이므로")
    print("      단측 p = (55+11+1)/2048 = 67/2048 = 약 0.033")
    print("      양측 p = 약 0.065")
    print("      -> 단측 0.05 기준이면 유의, 양측이면 아니다. 그래서 실습 3 에서")
    print("         단측/양측과 유의 수준을 **미리** 정해 둬야 한다. 결과를 본 뒤")
    print("         고르면 결론이 선택에 따라 뒤집힌다.")
    print()
    print("  (3) 짝지음의 이점: 같은 초기 배치끼리 비교되므로 task 난이도 편차가")
    print("      상쇄된다. 독립 두 집단으로 보면 그 편차가 잡음으로 들어간다.")
    print("      단 이 예에서는 두 방법의 p 값이 비슷하게 나온다(약 0.065-0.075) --")
    print("      짝지음의 이점은 seed 별 난이도 편차가 클 때 커진다.")
    print("      과장하지 말고, 짝지음을 쓰는 주된 이유는 '설계가 이미 짝지어져")
    print("      있으므로 그에 맞는 분석을 한다' 는 정합성이라고 적는 편이 정확하다.")


